/**
 * Converts Traditional Chinese text into Simplified Chinese accurately for HK Insurance terminology.
 */
export function toSimplifiedChinese(input: string): string {
  if (!input) return '';
  let result = input;
  for (const [trad, simp] of TRAD_TO_SIMP_PHRASES) {
    if (result.includes(trad)) {
      result = result.split(trad).join(simp);
    }
  }
  let out = '';
  for (let i = 0; i < result.length; i++) {
    const ch = result[i];
    out += TRAD_TO_SIMP_CHAR_MAP[ch] ?? ch;
  }
  return out;
}

/**
 * Selects the right text string given the active language:
 * - 'en' -> English text
 * - 'zh-HK' (ZN) -> Traditional Chinese text
 * - 'zh-CN' (CN) -> Simplified Chinese text (either explicit zhCn or converted from zhHk)
 */
export function pickLangText(
  lang: AppLanguage,
  en: string,
  zhHk: string,
  zhCn?: string
): string {
  if (lang === 'en') return en;
  if (lang === 'zh-CN') return zhCn ?? toSimplifiedChinese(zhHk);
  return zhHk;
}

/**
 * Localizes an InsurancePlan's display fields for EN, ZN (zh-HK), or CN (zh-CN).
 */
export function localizePlanStrings(plan: InsurancePlan, lang: AppLanguage) {
  const insurerName = pickLangText(lang, plan.insurerNameEn, plan.insurerNameZh);
  const planName = pickLangText(lang, plan.nameEn, plan.nameZh);
  const secondaryPlanName = lang === 'en' ? plan.nameZh : plan.nameEn;
  const categoryLabel = pickLangText(lang, plan.categoryLabelEn, plan.categoryLabelZh);
  const rawZhHighlights =
    plan.keyHighlightsZh && plan.keyHighlightsZh.length > 0
      ? plan.keyHighlightsZh
      : plan.highlights || plan.keyHighlightsEn;
  const highlights =
    lang === 'en'
      ? plan.keyHighlightsEn
      : lang === 'zh-CN'
      ? rawZhHighlights.map((h) => toSimplifiedChinese(h))
      : rawZhHighlights;

  return {
    insurerName,
    planName,
    secondaryPlanName,
    categoryLabel,
    highlights,
  };
}

